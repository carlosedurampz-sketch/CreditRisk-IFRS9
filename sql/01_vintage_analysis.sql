-- ============================================================================
-- 01_vintage_analysis.sql — Vintage (cosechas) analysis
-- ============================================================================
-- WHAT THIS DOES
--   A "vintage" is a cohort of loans originated in the same month.
--   Tracking each vintage's default / delinquency rate as it ages
--   (months on book, MOB) is the first thing a portfolio analyst
--   looks at: it separates "this cohort was bad from the start"
--   (underwriting) from "the whole portfolio got worse this month"
--   (macro / collections).
--
-- TABLES USED (see data/synthetic/, generated by src/generate_synthetic.py)
--   loans      : one row per loan — loan_id, origination_month, default_12m, ...
--   snapshots  : one row per loan-month — loan_id, months_on_book, dpd_bucket, ...
--
-- HOW TO READ THE OUTPUT
--   Each row is (origination_month, months_on_book). The columns are:
--     loans_active     — loans of that vintage observed at that MOB
--     share_30plus     — % in 30+ DPD at that MOB  (early delinquency)
--     share_90plus     — % in 90+ DPD at that MOB  (severe delinquency)
--     cum_default_rate — % of the vintage ever 90+ DPD up to that MOB
--   A healthy book shows curves that rise and then flatten; a vintage
--   whose curve sits clearly above its neighbours at the same MOB is
--   a candidate for an underwriting review.
--
-- NOTE ON MY SQL LEVEL (honest note, see README "About the author"):
--   I am strengthening SQL with this project. The queries below use
--   window functions (SUM() OVER ... / LAG()) and CTEs deliberately,
--   and every step is commented so a reviewer can follow the logic.
--   They run on SQLite, PostgreSQL and DuckDB with no changes, and
--   the Python pipeline validates the same numbers with pandas.
-- ============================================================================

-- --- Step 1: one row per (vintage, MOB) with bucket counts -------------------
-- COUNT(*) FILTER (WHERE ...) counts only rows matching the condition;
-- it is clearer than SUM(CASE WHEN ... THEN 1 ELSE 0 END) for this.
WITH monthly AS (
    SELECT
        s.origination_month,
        s.months_on_book,
        COUNT(*) AS loans_active,
        COUNT(*) FILTER (WHERE s.dpd_bucket IN ('30', '60', '90+')) AS n_30plus,
        COUNT(*) FILTER (WHERE s.dpd_bucket = '90+') AS n_90plus
    FROM snapshots AS s
    GROUP BY s.origination_month, s.months_on_book
),

-- --- Step 2: rates + cumulative 90+ rate within each vintage -----------------
-- SUM(n_90plus) OVER (PARTITION BY origination_month ORDER BY months_on_book)
-- is a running total: "how many of this vintage have *ever* hit 90+ so far".
-- Dividing by the vintage's original size gives the cumulative default curve.
vintage AS (
    SELECT
        origination_month,
        months_on_book,
        loans_active,
        ROUND(100.0 * n_30plus / loans_active, 2) AS share_30plus_pct,
        ROUND(100.0 * n_90plus / loans_active, 2) AS share_90plus_pct,
        ROUND(100.0 * SUM(n_90plus) OVER (
            PARTITION BY origination_month
            ORDER BY months_on_book
        ) / MAX(loans_active) OVER (PARTITION BY origination_month), 2)
            AS cum_90plus_pct
    FROM monthly
)

SELECT *
FROM vintage
WHERE months_on_book IN (3, 6, 9, 12, 18, 24)  -- standard reporting MOBs
ORDER BY origination_month, months_on_book;

